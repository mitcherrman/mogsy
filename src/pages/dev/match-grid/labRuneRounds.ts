/**
 * MATCH GRID — the RUNE → RUNE TREE authority adapter (GM-M1's first family).
 *
 * This is an ADAPTER, not a second authority. It reads the rune table the
 * frontend already ships (`live-esports/runeData.ts`, generated from Data
 * Dragon 16.19.1 and the only rune art mapping in the repo) and, when the
 * backend is reachable, narrows the playable roster to the runes the backend's
 * own `runes` table (`GET /api/meta/runes`, the production rune authority
 * behind the Practice rune families) ALSO knows and agrees on. Every M1 round
 * can therefore be regenerated by production from its own table; nothing is
 * hand-copied here. See docs/MATCH_GRID_AUTHORITY_AUDIT.md for the provenance
 * findings, including why the frontend table is legacy-lineage from the
 * backend's point of view.
 *
 * The CANONICAL MAPPING NEVER ENTERS `MatchPublic`. `buildRuneRound` returns it
 * separately as `RuneSecret`, which the M1 harness holds in a closure and the
 * production module would hold server-side in the private payload.
 */
import { RUNE_PERKS, RUNE_TREES, type RunePerk } from "@/lib/live-esports/runeData";
import { resolveQuizAssetUrl } from "@/lib/quiz/api";
import type { MatchEntity, MatchFact, MatchGroup, MatchPublic, MatchResponse, MatchReveal } from "@/lib/match-grid/contract";

/** What `runeData.ts` says it was generated from. Shown as the reveal's source line. */
export const RUNE_SOURCE = "Data Dragon 16.19.1 · runesReforged";

/** The five trees in the client's own order. A tree's hue is its public identity, not a hint. */
export const RUNE_TREE_ORDER: readonly { id: number; hue: number; glyph: string }[] = [
  { id: 8000, hue: 44, glyph: "precision" },
  { id: 8100, hue: 356, glyph: "domination" },
  { id: 8200, hue: 252, glyph: "sorcery" },
  { id: 8400, hue: 142, glyph: "resolve" },
  { id: 8300, hue: 186, glyph: "inspiration" },
];

// ---------------------------------------------------------------- roster

export interface BackendRuneRow { rune_name: string; tree_name: string; rune_type: string }

export interface RuneRoster {
  /** Perk ids M1 may deal. */
  ids: ReadonlySet<number>;
  status:
    | { kind: "agreed"; backendRows: number; agreed: number; backendOnly: string[]; disagreed: string[] }
    | { kind: "frontend-only"; reason: string };
}

/** The whole frontend table, used when the backend cannot be asked. */
export function frontendOnlyRoster(reason: string): RuneRoster {
  return { ids: new Set(Object.keys(RUNE_PERKS).map(Number)), status: { kind: "frontend-only", reason } };
}

/** Narrow to the runes both tables know, and agree on tree AND keystone status. */
export function intersectRoster(rows: readonly BackendRuneRow[]): RuneRoster {
  const byName = new Map(Object.values(RUNE_PERKS).map((p) => [p.name, p]));
  const ids = new Set<number>();
  const backendOnly: string[] = [];
  const disagreed: string[] = [];
  for (const r of rows) {
    const perk = byName.get(r.rune_name);
    if (!perk) { backendOnly.push(r.rune_name); continue; }
    const tree = RUNE_TREES[perk.tree]?.name;
    const keystone = r.rune_type === "keystone";
    if (tree !== r.tree_name || keystone !== perk.keystone) { disagreed.push(r.rune_name); continue; }
    ids.add(perk.id);
  }
  return { ids, status: { kind: "agreed", backendRows: rows.length, agreed: ids.size, backendOnly, disagreed } };
}

export async function fetchBackendRunes(baseUrl: string, fetchImpl: typeof fetch = fetch): Promise<BackendRuneRow[]> {
  const res = await fetchImpl(`${baseUrl.replace(/\/+$/, "")}/api/meta/runes`);
  if (!res.ok) throw new Error(`runes endpoint ${res.status}`);
  const json = (await res.json()) as { ok?: boolean; runes?: BackendRuneRow[] };
  if (!json.ok || !Array.isArray(json.runes)) throw new Error("runes endpoint: malformed body");
  return json.runes;
}

