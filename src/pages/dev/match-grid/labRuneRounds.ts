export interface RuneSecret {
  /** Entity token → group token. Reveal-only. */
  canonical: Readonly<Record<string, string>>;
  facts: Readonly<Record<string, readonly MatchFact[]>>;
  source: string;
  /** For the harness chrome only. */
  perkIds: Readonly<Record<string, number>>;
}

/** Deterministic, ANSWER-INDEPENDENT ordering: seeded by the round id, never by the relation. */
export function seededShuffle<T>(list: readonly T[], seed: string): T[] {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) h = Math.imul(h ^ seed.charCodeAt(i), 16777619) >>> 0;
  const rand = () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507) >>> 0;
    h = Math.imul(h ^ (h >>> 13), 3266489909) >>> 0;
    return ((h ^= h >>> 16) >>> 0) / 4294967296;
  };
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

function perkMedia(p: RunePerk) {
  return p.icon ? { src: resolveQuizAssetUrl(p.icon) ?? null, alt: "" } : null;
}

export function buildRuneRound(spec: RuneRoundSpec, roster: RuneRoster): { content: MatchPublic; secret: RuneSecret } {
  if (spec.trees < 2 || spec.trees > RUNE_TREE_ORDER.length || spec.perTree.length !== spec.trees) {
    throw new Error(`rune round "${spec.id}": trees/perTree mismatch`);
  }
  const trees = seededShuffle(RUNE_TREE_ORDER, `${spec.seed}:trees`).slice(0, spec.trees)
    .sort((a, b) => RUNE_TREE_ORDER.findIndex((t) => t.id === a.id) - RUNE_TREE_ORDER.findIndex((t) => t.id === b.id));
  const groups: MatchGroup[] = trees.map((t, i) => ({
    token: `d${i}`,
    label: RUNE_TREES[t.id].name,
    hue: t.hue,
    glyph: t.glyph,
  }));
  const dealt: { perk: RunePerk; group: string }[] = [];
  trees.forEach((t, i) => {
    const pool = Object.values(RUNE_PERKS)
      .filter((p) => p.tree === t.id && roster.ids.has(p.id) && (!spec.keystonesOnly || p.keystone))
      .sort((a, b) => a.id - b.id);
    const picks = seededShuffle(pool, `${spec.seed}:${t.id}`).slice(0, spec.perTree[i]);
    if (picks.length < spec.perTree[i]) {
      throw new Error(`rune round "${spec.id}": ${RUNE_TREES[t.id].name} has only ${pool.length} eligible runes in this roster`);
    }
    picks.forEach((perk) => dealt.push({ perk, group: groups[i].token }));
  });
  const shuffled = seededShuffle(dealt, `${spec.seed}:deal`);
  const entities: MatchEntity[] = [];
  const canonical: Record<string, string> = {};
  const facts: Record<string, MatchFact[]> = {};
  const perkIds: Record<string, number> = {};
  shuffled.forEach((d, i) => {
    const token = `s${i}`;
    entities.push({ token, label: d.perk.name, media: perkMedia(d.perk) });
    canonical[token] = d.group;
    perkIds[token] = d.perk.id;
    // The tree itself is the group the reveal seats the rune in, so the only
    // extra fact is the rune's slot status (keystone or minor), which both
    // tables agree on for the agreed roster.
    facts[token] = [{ label: "Slot", value: d.perk.keystone ? "Keystone" : "Minor rune" }];
  });
  const content: MatchPublic = {
    prompt: "Seat each rune in the tree it belongs to.",
    context: `Match Grid · Rune → Rune tree · ${spec.title}`,
    entityNoun: "rune",
    groupNoun: "rune tree",
    entities,
    groups,
    membership: "one",
  };
  return { content, secret: { canonical, facts, source: RUNE_SOURCE, perkIds } };
}

/**
 * PROTOTYPE-ONLY grader. In production this is the server's job (the
 * Reconstruct precedent: `grade_assembly` lives in `ranked_modules/`), and the
 * browser only displays the reveal it is handed. The M1 harness calls this
 * from a closure the primitive cannot reach, after Lock, and passes only the
 * resulting `MatchReveal` down. Nothing in `components/match-grid` imports it.
 */
export function gradeRuneRound(secret: RuneSecret, response: MatchResponse): MatchReveal {
  const assignments: Record<string, string> = {};
  const entityCorrect: Record<string, boolean> = {};
  const canonical: Record<string, readonly string[]> = {};
  for (const a of response.assignments) {
    assignments[a.entity] = a.group;
    entityCorrect[a.entity] = secret.canonical[a.entity] === a.group;
  }
  for (const [entity, group] of Object.entries(secret.canonical)) {
    canonical[entity] = [group];
    if (!(entity in entityCorrect)) entityCorrect[entity] = false;
  }
  const isCorrect = Object.values(entityCorrect).every(Boolean);
  return { assignments, canonical, entityCorrect, isCorrect, facts: secret.facts, source: secret.source };
}
