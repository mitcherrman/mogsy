export interface RuneRoundSpec {
  id: string;
  title: string;
  /** How many trees receive seals (2–5). */
  trees: number;
  /** Runes dealt per tree, in seal order; a 0 leaves that seal empty on purpose. */
  perTree: readonly number[];
  keystonesOnly?: boolean;
  seed: string;
}

